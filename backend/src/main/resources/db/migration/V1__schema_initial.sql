-- Schéma de départ de l'app. Compatible PostgreSQL (prod) et H2 (local, tests).
-- Ne jamais modifier une migration déjà appliquée : ajouter un fichier V2__..., V3__..., etc.

create table utilisateur (
    id                 bigint generated by default as identity primary key,
    email              varchar(120) not null unique,
    mot_de_passe_hache varchar(255) not null
);

create table objectif (
    id                bigint generated by default as identity primary key,
    utilisateur_id    bigint       not null references utilisateur (id),
    nom               varchar(50)  not null,
    categorie         varchar(20)  not null,
    type_frequence    varchar(20)  not null,
    cible             integer      not null,
    heure             time         not null,
    couleur           varchar(7)   not null,
    archive           boolean      not null default false,
    date_creation     date         not null,
    mesure            varchar(20),
    objectif_quantite double precision,
    rappel_auto       boolean,
    cible_depuis      date,
    code_partage      varchar(12) unique
);
create index objectif_utilisateur_idx on objectif (utilisateur_id);

create table validation (
    objectif_id   bigint  not null references objectif (id),
    jour          date    not null,
    type_seance   varchar(255),
    duree_minutes integer,
    ressenti      varchar(255),
    ponctualite   varchar(255),
    reveil        varchar(255),
    heure_coche   time,
    quantite      double precision
);
create index validation_objectif_idx on validation (objectif_id);

create table binome (
    id             bigint generated by default as identity primary key,
    utilisateur_id bigint not null references utilisateur (id),
    objectif_id    bigint not null references objectif (id),
    unique (utilisateur_id, objectif_id)
);
