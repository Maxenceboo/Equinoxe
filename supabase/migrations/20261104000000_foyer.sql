-- Foyer : la famille qui avance ensemble. Un utilisateur appartient à un seul foyer.
-- On ne partage que le strict nécessaire : prénom, nombre de coches et d'objectifs tenus de la semaine.

create table public.foyer (
  id               bigint generated by default as identity primary key,
  nom              text not null check (char_length(trim(nom)) between 1 and 40),
  code             text not null unique,
  recompense       text check (char_length(recompense) <= 80),
  objectif_semaine integer not null default 20 check (objectif_semaine between 1 and 500),
  cree_le          timestamptz not null default now()
);

create table public.foyer_membre (
  foyer_id       bigint not null references public.foyer (id) on delete cascade,
  utilisateur_id uuid not null unique default auth.uid() references auth.users (id) on delete cascade,
  prenom         text not null check (char_length(trim(prenom)) between 1 and 30),
  parent         boolean not null default false,
  depuis         timestamptz not null default now(),
  primary key (foyer_id, utilisateur_id)
);

-- Encouragements en un tap entre membres (pas de messagerie libre)
create table public.encouragement (
  id        bigint generated by default as identity primary key,
  foyer_id  bigint not null references public.foyer (id) on delete cascade,
  de        uuid not null default auth.uid() references auth.users (id) on delete cascade,
  a         uuid not null references auth.users (id) on delete cascade,
  type      text not null check (type in ('BRAVO', 'COURAGE', 'FIER', 'MERCI')),
  cree_le   timestamptz not null default now(),
  vu        boolean not null default false
);
create index encouragement_a_idx on public.encouragement (a, vu);

-- Foyer de l'utilisateur connecté (null s'il n'en a pas)
create function public.mon_foyer()
returns bigint language sql stable security definer set search_path = '' as $$
  select foyer_id from public.foyer_membre where utilisateur_id = auth.uid();
$$;

create function public.suis_parent()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select parent from public.foyer_membre where utilisateur_id = auth.uid()), false);
$$;

alter table public.foyer enable row level security;
alter table public.foyer_membre enable row level security;
alter table public.encouragement enable row level security;

create policy "mon foyer, lecture" on public.foyer
  for select to authenticated using (id = (select public.mon_foyer()));
create policy "mon foyer, réglages par un parent" on public.foyer
  for update to authenticated
  using (id = (select public.mon_foyer()) and (select public.suis_parent()))
  with check (id = (select public.mon_foyer()));

create policy "membres de mon foyer" on public.foyer_membre
  for select to authenticated using (foyer_id = (select public.mon_foyer()));
create policy "changer mon prénom" on public.foyer_membre
  for update to authenticated
  using (utilisateur_id = (select auth.uid()))
  with check (utilisateur_id = (select auth.uid()) and foyer_id = (select public.mon_foyer()));
create policy "quitter mon foyer" on public.foyer_membre
  for delete to authenticated using (utilisateur_id = (select auth.uid()));

create policy "mes encouragements" on public.encouragement
  for select to authenticated using (a = (select auth.uid()) or de = (select auth.uid()));
create policy "encourager un membre" on public.encouragement
  for insert to authenticated
  with check (
    de = (select auth.uid()) and a <> (select auth.uid()) and foyer_id = (select public.mon_foyer())
    and exists (select 1 from public.foyer_membre m where m.foyer_id = encouragement.foyer_id and m.utilisateur_id = encouragement.a)
  );
create policy "marquer comme vu" on public.encouragement
  for update to authenticated using (a = (select auth.uid())) with check (a = (select auth.uid()));

-- Le statut de parent et le foyer d'un membre ne se changent pas directement
create function public.proteger_membre()
returns trigger language plpgsql set search_path = '' as $$
begin
  if (new.parent is distinct from old.parent or new.foyer_id is distinct from old.foyer_id)
     and current_user in ('authenticated', 'anon') then
    raise exception 'Modification non autorisée' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger proteger_membre before update on public.foyer_membre
  for each row execute function public.proteger_membre();

create function public.proteger_code_foyer()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.code is distinct from old.code and current_user in ('authenticated', 'anon') then
    raise exception 'Le code du foyer ne se modifie pas directement' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger proteger_code_foyer before update on public.foyer
  for each row execute function public.proteger_code_foyer();

-- Crée un foyer dont on est parent. Renvoie son code à 6 chiffres.
create function public.creer_foyer(p_nom text, p_prenom text)
returns text language plpgsql security definer set search_path = '' as $$
declare
  v_code text;
  v_id bigint;
begin
  if auth.uid() is null then raise exception 'Connexion requise' using errcode = '42501'; end if;
  if exists (select 1 from public.foyer_membre where utilisateur_id = auth.uid()) then
    raise exception 'Tu fais déjà partie d''un foyer.' using errcode = '22023';
  end if;
  loop
    v_code := lpad(floor(random() * 1000000)::int::text, 6, '0');
    exit when not exists (select 1 from public.foyer where code = v_code);
  end loop;
  insert into public.foyer (nom, code) values (trim(p_nom), v_code) returning id into v_id;
  insert into public.foyer_membre (foyer_id, utilisateur_id, prenom, parent) values (v_id, auth.uid(), trim(p_prenom), true);
  return v_code;
end $$;

-- Rejoint un foyer grâce à son code. p_parent : rejoindre comme parent (l'autre parent du foyer).
create function public.rejoindre_foyer(p_code text, p_prenom text, p_parent boolean default false)
returns bigint language plpgsql security definer set search_path = '' as $$
declare
  v_id bigint;
begin
  if auth.uid() is null then raise exception 'Connexion requise' using errcode = '42501'; end if;
  select id into v_id from public.foyer where code = regexp_replace(p_code, '\D', '', 'g');
  if not found then
    raise exception 'Aucun foyer avec ce code. Vérifie les 6 chiffres.' using errcode = 'P0002';
  end if;
  if exists (select 1 from public.foyer_membre where utilisateur_id = auth.uid()) then
    raise exception 'Tu fais déjà partie d''un foyer.' using errcode = '22023';
  end if;
  insert into public.foyer_membre (foyer_id, utilisateur_id, prenom, parent) values (v_id, auth.uid(), trim(p_prenom), p_parent);
  return v_id;
end $$;

-- La semaine du foyer : pour chaque membre, ses coches et ses objectifs tenus (pas le détail).
create function public.foyer_semaine(p_lundi date)
returns table (utilisateur_id uuid, prenom text, parent boolean, moi boolean, coches integer, objectifs integer, tenus integer)
language sql stable security definer set search_path = '' as $$
  select m.utilisateur_id, m.prenom, m.parent, m.utilisateur_id = auth.uid(),
         coalesce(sum(s.n), 0)::int,
         count(s.objectif_id)::int,
         count(*) filter (where s.n >= s.cible)::int
    from public.foyer_membre m
    left join lateral (
      select o.id as objectif_id, case when o.type_frequence = 'QUOTIDIEN' then 7 else o.cible end as cible,
             (select count(*) from public.validation v where v.objectif_id = o.id and v.jour between p_lundi and p_lundi + 6) as n
        from public.objectif o
       where o.utilisateur_id = m.utilisateur_id and not o.archive
    ) s on true
   where m.foyer_id = public.mon_foyer()
   group by m.utilisateur_id, m.prenom, m.parent, m.depuis
   order by m.depuis;
$$;

revoke execute on function public.mon_foyer() from public, anon;
revoke execute on function public.suis_parent() from public, anon;
revoke execute on function public.creer_foyer(text, text) from public, anon;
revoke execute on function public.rejoindre_foyer(text, text, boolean) from public, anon;
revoke execute on function public.foyer_semaine(date) from public, anon;
grant execute on function public.mon_foyer() to authenticated;
grant execute on function public.suis_parent() to authenticated;
grant execute on function public.creer_foyer(text, text) to authenticated;
grant execute on function public.rejoindre_foyer(text, text, boolean) to authenticated;
grant execute on function public.foyer_semaine(date) to authenticated;

grant select on public.foyer to authenticated;
grant update (nom, recompense, objectif_semaine) on public.foyer to authenticated;
grant select, delete on public.foyer_membre to authenticated;
grant update (prenom) on public.foyer_membre to authenticated;
grant select on public.encouragement to authenticated;
grant insert (foyer_id, a, type) on public.encouragement to authenticated;
grant update (vu) on public.encouragement to authenticated;
grant usage on all sequences in schema public to authenticated;
