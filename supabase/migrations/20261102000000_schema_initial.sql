-- Données de l'app « Objectifs perso ».
-- Chaque utilisateur ne voit et ne modifie que ses objectifs (Row Level Security).
-- Le binôme passe par des fonctions dédiées qui ne donnent à l'ami que le strict nécessaire.

create table public.objectif (
  id                bigint generated by default as identity primary key,
  utilisateur_id    uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nom               text not null check (char_length(trim(nom)) between 1 and 50),
  categorie         text not null check (categorie in ('SPORT', 'SOMMEIL', 'AUTRE')),
  type_frequence    text not null check (type_frequence in ('PAR_SEMAINE', 'QUOTIDIEN')),
  cible             integer not null check (cible between 1 and 7),
  heure             time not null,
  couleur           text not null default '#ffffff',
  archive           boolean not null default false,
  date_creation     date not null default current_date,
  mesure            text check (mesure in ('KM', 'PAGES', 'MINUTES')),
  objectif_quantite double precision check (objectif_quantite > 0),
  rappel_auto       boolean not null default false,
  -- Dernier changement de cible (null s'il n'a jamais changé) : les conseils de cible ne regardent que l'après
  cible_depuis      date,
  code_partage      text unique
);
create index objectif_utilisateur_idx on public.objectif (utilisateur_id);

create table public.validation (
  objectif_id   bigint not null references public.objectif (id) on delete cascade,
  jour          date not null,
  type_seance   text,
  duree_minutes integer,
  ressenti      text,
  ponctualite   text,
  reveil        text,
  -- Heure de la coche, seulement si elle a été faite le jour même (sert à l'heure habituelle)
  heure_coche   time,
  quantite      double precision check (quantite >= 0 and quantite <= 100000),
  primary key (objectif_id, jour)
);

create table public.binome (
  utilisateur_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  objectif_id    bigint not null references public.objectif (id) on delete cascade,
  depuis         timestamptz not null default now(),
  primary key (utilisateur_id, objectif_id)
);
create index binome_objectif_idx on public.binome (objectif_id);

-- ---------- Sécurité : chacun chez soi ----------
alter table public.objectif enable row level security;
alter table public.validation enable row level security;
alter table public.binome enable row level security;

create policy "mes objectifs" on public.objectif
  for all to authenticated
  using (utilisateur_id = (select auth.uid()))
  with check (utilisateur_id = (select auth.uid()));

create policy "mes coches" on public.validation
  for all to authenticated
  using (exists (select 1 from public.objectif o where o.id = objectif_id and o.utilisateur_id = (select auth.uid())))
  with check (exists (select 1 from public.objectif o where o.id = objectif_id and o.utilisateur_id = (select auth.uid())));

-- On voit et on quitte ses binômes ; on n'en crée que par code (fonction rejoindre_binome)
create policy "mes binômes, lecture" on public.binome
  for select to authenticated using (utilisateur_id = (select auth.uid()));
create policy "mes binômes, quitter" on public.binome
  for delete to authenticated using (utilisateur_id = (select auth.uid()));

-- Le code de partage ne se modifie que par partager_objectif (qui tourne avec les droits du propriétaire)
create function public.proteger_code_partage()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.code_partage is distinct from old.code_partage and current_user in ('authenticated', 'anon') then
    raise exception 'Le code de partage ne se modifie pas directement' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger proteger_code_partage before update on public.objectif
  for each row execute function public.proteger_code_partage();

-- ---------- Binôme ----------

-- Donne (et crée au premier appel) le code de partage d'un de ses objectifs, avec le nombre d'amis qui le suivent.
create function public.partager_objectif(p_objectif_id bigint)
returns table (code text, abonnes integer)
language plpgsql security definer set search_path = '' as $$
declare
  v_code text;
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
begin
  select o.code_partage into v_code from public.objectif o
   where o.id = p_objectif_id and o.utilisateur_id = auth.uid();
  if not found then
    raise exception 'Objectif introuvable' using errcode = 'P0002';
  end if;
  while v_code is null loop
    v_code := '';
    for i in 1..6 loop
      v_code := v_code || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1);
    end loop;
    if exists (select 1 from public.objectif where code_partage = v_code) then
      v_code := null;
    else
      update public.objectif set code_partage = v_code where id = p_objectif_id;
    end if;
  end loop;
  return query select v_code, (select count(*)::int from public.binome b where b.objectif_id = p_objectif_id);
end $$;

-- Suit l'objectif d'un ami grâce à son code. Renvoie l'identifiant de l'objectif suivi.
create function public.rejoindre_binome(p_code text)
returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_objectif public.objectif;
begin
  select * into v_objectif from public.objectif
   where code_partage = upper(trim(p_code)) and not archive;
  if not found then
    raise exception 'Aucun objectif partagé avec ce code' using errcode = 'P0002';
  end if;
  if v_objectif.utilisateur_id = auth.uid() then
    raise exception 'C''est ton propre objectif : partage ce code à un ami.' using errcode = '22023';
  end if;
  insert into public.binome (utilisateur_id, objectif_id) values (auth.uid(), v_objectif.id)
  on conflict do nothing;
  return v_objectif.id;
end $$;

-- Objectifs d'amis suivis : seulement le nom, la cible et les jours cochés (pas les détails),
-- et le nom de l'ami (ce qu'il y a avant l'arobase de son email).
create function public.objectifs_suivis()
returns table (
  objectif_id bigint, nom text, ami text, categorie text, type_frequence text, cible integer,
  date_creation date, jours date[]
)
language sql stable security definer set search_path = '' as $$
  select o.id, o.nom,
         initcap(split_part(u.email, '@', 1)),
         o.categorie, o.type_frequence, o.cible, o.date_creation,
         coalesce((select array_agg(v.jour order by v.jour) from public.validation v where v.objectif_id = o.id), '{}')
    from public.binome b
    join public.objectif o on o.id = b.objectif_id and not o.archive
    join auth.users u on u.id = o.utilisateur_id
   where b.utilisateur_id = auth.uid()
   order by b.depuis;
$$;

revoke execute on function public.partager_objectif(bigint) from public, anon;
revoke execute on function public.rejoindre_binome(text) from public, anon;
revoke execute on function public.objectifs_suivis() from public, anon;
grant execute on function public.partager_objectif(bigint) to authenticated;
grant execute on function public.rejoindre_binome(text) to authenticated;
grant execute on function public.objectifs_suivis() to authenticated;
