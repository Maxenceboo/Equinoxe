-- Boutique : les points se dépensent en jokers en plus et en palettes de couleurs pour les animations.
-- Le solde est calculé dans l'app (points gagnés moins achats) ; la base garde seulement les achats.

create table public.joker_achete (
  id             bigint generated by default as identity primary key,
  utilisateur_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  objectif_id    bigint not null references public.objectif (id) on delete cascade,
  mois           text not null check (mois ~ '^\d{4}-\d{2}$'),
  cree_le        timestamptz not null default now()
);
create index joker_achete_objectif_idx on public.joker_achete (objectif_id);

create table public.palette_achetee (
  utilisateur_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  palette        text not null check (palette in ('OCEAN', 'FORET', 'BRAISE', 'PRISME')),
  cree_le        timestamptz not null default now(),
  primary key (utilisateur_id, palette)
);

alter table public.joker_achete enable row level security;
alter table public.palette_achetee enable row level security;

create policy "mes jokers" on public.joker_achete
  for select to authenticated using (utilisateur_id = (select auth.uid()));
create policy "acheter un joker pour mon objectif" on public.joker_achete
  for insert to authenticated
  with check (
    utilisateur_id = (select auth.uid())
    and exists (select 1 from public.objectif o where o.id = objectif_id and o.utilisateur_id = (select auth.uid()))
  );

create policy "mes palettes" on public.palette_achetee
  for select to authenticated using (utilisateur_id = (select auth.uid()));
create policy "acheter une palette" on public.palette_achetee
  for insert to authenticated with check (utilisateur_id = (select auth.uid()));

grant select, insert (objectif_id, mois) on public.joker_achete to authenticated;
grant select, insert (palette) on public.palette_achetee to authenticated;
